// This file lives in config/ but is COPIED into .src/site/ by `mise run dev`, so its imports
// resolve from that location via pnpm (published packages, no monorepo). That is why
// `mise run check -- --site` type-checks the copy rather than this path.
//
// It used to carry `// @ts-nocheck` for "TS errors for missing modules are false positives".
// That went stale: with the suppression removed the file typechecks clean (`tsc --checkJs`
// reports nothing, and `astro check` loads it without complaint), so the suppression was only
// hiding real errors from editors.
//
// The host site is the official starter-cloudflare template (see docs/plans/done/0007-emdash-1.1-templates-src-rework.md).
import cloudflare from "@astrojs/cloudflare";
import react from "@astrojs/react";
import { d1, r2, sandbox } from "@emdash-cms/cloudflare";
import { formsPlugin } from "@emdash-cms/plugin-forms";
import webhookNotifier from "@emdash-cms/plugin-webhook-notifier";
import { defineConfig } from "astro/config";
import emdash from "emdash/astro";
// Local plugins — every sandboxed plugin under plugins/. This module is GENERATED by
// `mise run dev`, so scaffolding or removing a plugin never
// means editing this file. With no local plugins it exports an empty list.
import { sandboxed as localSandboxed } from "./local-plugins.mjs";

export default defineConfig({
	output: "server",
	adapter: cloudflare(),
	image: {
		layout: "constrained",
		responsiveStyles: true,
	},
	integrations: [
		react(),
		emdash({
			// D1 binding name must match wrangler.jsonc. session: "auto" enables read replicas.
			database: d1({ binding: "DB", session: "auto" }),
			// R2 storage for media
			storage: r2({ binding: "MEDIA" }),

			// Native plugins (run in the host worker)
			plugins: [formsPlugin()],

			// Sandboxed plugins (run in isolated Worker isolates via the LOADER binding).
			sandboxed: [webhookNotifier, ...localSandboxed],
			sandboxRunner: sandbox(),

			// The plugin registry — the current name for the plugin marketplace.
			// The hosted registry, unless `mise run registry:up` has a local one answering — then the
			// dev server is started with EMDASH_REGISTRY_URL pointing at it.
			registry: process.env.EMDASH_REGISTRY_URL ?? "https://registry.emdashcms.com",

			// MCP is enabled by default at /_emdash/api/mcp (Bearer token required).
		}),
	],
	devToolbar: { enabled: false },
});
